const mongoose = require("mongoose");

const electricityTokenSchema = new mongoose.Schema(
  {
    tenant: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    meterNumber: {
      type: String,
      required: true,
    },
    amountPaid: {
      type: Number,
      required: true, // Range 20000 - 100000
    },
    commissionDeducted: {
      type: Number, // 5% commission to Momas / Company
      required: true,
    },
    tokenCode: {
      type: String,
      required: true, // 20-digit STS token generated by Momas API
    },
    units: {
      type: String,
      default: "kWh",
    },
    status: {
      type: String,
      enum: ["success", "failed", "pending"],
      default: "success",
    },
    reference: {
      type: String,
      required: true,
      unique: true,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model("ElectricityToken", electricityTokenSchema);